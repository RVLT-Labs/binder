#!/usr/bin/env bash
# Writes deploy/.env (gitignored) for a LOCAL run of deploy/docker-compose.yml: the variables Coolify
# generates in production, with fresh random values, plus local origins. Never reuse this file in
# production, and never commit it. Refuses to overwrite an existing file unless --force is given.
#
#   deploy/scripts/gen-env.sh [--force]
set -euo pipefail

ENV_FILE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/.env"
if [[ -e "$ENV_FILE" && "${1:-}" != "--force" ]]; then
  echo "$ENV_FILE already exists; pass --force to replace it" >&2
  exit 1
fi

alnum() { LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c "$1"; }

umask 077
cat >"$ENV_FILE" <<ENV
# Generated by deploy/scripts/gen-env.sh for local runs. Gitignored.
SERVICE_PASSWORD_POSTGRES=$(alnum 32)
SERVICE_PASSWORD_POWERSYNC=$(alnum 32)
SERVICE_BASE64_64_AUTH=$(alnum 64)
SERVICE_HEX_64_PSJWT=$(openssl rand -hex 32)
APP_ORIGIN=http://localhost
POWERSYNC_URL=http://localhost:18080
ENV
echo "wrote $ENV_FILE"
